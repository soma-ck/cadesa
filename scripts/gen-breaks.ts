/**
 * Generate src/engine/breaks.generated.ts: Chromium's line-break opportunities between every pair
 * of non-space characters in the measured set, measured once (like the font metrics).
 *
 * Chromium decides ASCII pairs with its own table and asks ICU (UAX #14) otherwise, and a few
 * rules look one character further back (e.g. "-" before a digit breaks only after an ASCII
 * letter or digit). So each pair is measured after five kinds of preceding character: none or a
 * space, an ASCII letter, an ASCII digit, another letter, and anything else.
 *
 * Measured for ordinary text, for `word-break: break-all` and for `line-break: anywhere` (each its
 * own table), and for `word-break: keep-all`, which must be the same as ordinary text for these
 * characters (it only keeps CJK letters together).
 *
 *   npm run breaks
 */
import { readFileSync, writeFileSync } from "node:fs";
import { chromium } from "playwright";
import { CHARS, findChrome } from "../src/metrics.js";

export const CONTEXTS = ["", "a", "1", "é", "."];
const chars = [...CHARS].filter((c) => c !== " ");
const n = chars.length;

const font = readFileSync("fonts/InterVariable-latin.woff2").toString("base64");
const browser = await chromium.launch({ executablePath: findChrome() });

/** The break table of text with these extra declarations. */
async function measure(extra: string): Promise<Uint8Array> {
  const page = await browser.newPage();
  await page.setContent(
    `<style>@font-face{font-family:Inter;font-weight:100 900;src:url(data:font/woff2;base64,${font}) format("woff2")} div{font:400 20px/1 Inter;width:0;hyphens:manual;white-space:normal;overflow-wrap:normal;word-break:normal;line-break:auto;letter-spacing:normal;${extra}}</style><div id=d></div>`,
  );
  await page.evaluate("document.fonts.load('400 20px Inter')");
  const bits = new Uint8Array(Math.ceil((CONTEXTS.length * n * n) / 8));
  for (let k = 0; k < CONTEXTS.length; k++) {
    for (let i = 0; i < n; i++) {
      const row = (await page.evaluate(`((pre, p, qs) => {
        const d = document.getElementById('d');
        const lines = (s) => { d.textContent = s; return Math.round(d.getBoundingClientRect().height / 20); };
        const before = lines(pre + p);
        return qs.map((q) => lines(pre + p + q) > before);
      })(${JSON.stringify(CONTEXTS[k])}, ${JSON.stringify(chars[i])}, ${JSON.stringify(chars)})`)) as boolean[];
      row.forEach((b, j) => {
        if (!b) return;
        const bit = (k * n + i) * n + j;
        bits[bit >> 3] |= 1 << (bit & 7);
      });
    }
  }
  await page.close();
  return bits;
}

const [normal, breakAll, anywhere, keepAll] = await Promise.all([measure(""), measure("word-break:break-all"), measure("line-break:anywhere"), measure("word-break:keep-all")]);
const version = browser.version();
await browser.close();
if (!Buffer.from(keepAll).equals(Buffer.from(normal))) throw new Error("word-break: keep-all breaks these characters differently from ordinary text");
const b64 = (b: Uint8Array) => Buffer.from(b).toString("base64");

writeFileSync(
  "src/engine/breaks.generated.ts",
  `// Generated by scripts/gen-breaks.ts from Chromium ${version}. Do not edit.
// Bit ((context * N + a) * N + b) is set when Chromium may break between characters a and b of
// CHARS (without spaces), where context is what precedes a: none or a space, an ASCII letter, an
// ASCII digit, another letter, anything else. BREAKS: ordinary text (and word-break: keep-all,
// measured the same for these characters); BREAKS_ALL: word-break: break-all; BREAKS_ANYWHERE:
// line-break: anywhere.
export const BREAK_CHARS = ${JSON.stringify(chars.join(""))};
export const BREAKS = ${JSON.stringify(b64(normal))};
export const BREAKS_ALL = ${JSON.stringify(b64(breakAll))};
export const BREAKS_ANYWHERE = ${JSON.stringify(b64(anywhere))};
`,
);
console.log(`wrote src/engine/breaks.generated.ts: ${n} characters, ${CONTEXTS.length} contexts`);
